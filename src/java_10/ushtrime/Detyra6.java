package java_10.ushtrime;

public class Detyra6 {
    public static void main(String[] args) {
        for (int i = 1; i <= 100; i++) {
            System.out.printf("%d^2 = %d%n", i, (i * i));
        }

        System.out.println();

        // tabela e shumzimit
        int x = 8;

        for (int i = 1; i <= 10; i++) {
            System.out.printf("%d * %d = %d%n", i, x, (i * x));
        }
    }
}